//! The master command list: `cmd_info[]` of `interpreter.c`, in table order.
//!
//! Order is behaviour: `command_interpreter` takes the first entry whose name
//! the typed word is a prefix of, so `s` means `south` and `sa` means `say`
//! only because of where each sits in the list.
//!
//! Each row names the C function's effect for a *mob* as a [`Handler`]:
//! the commands the pack implements for NPCs, the ones that do nothing for an
//! NPC in the C (a display, a player-only toggle, a skill an NPC "has no idea
//! how" to use, a shop command outside a shop), and the few that do something
//! the pack does not model ([`Handler::Unmodelled`], counted when used).

/// `POS_DEAD` and the rest of the Diku position ladder, as the numbers the
/// table (and a social's position columns) use.
pub const DEAD: i32 = 0;
pub const MORTALLY_WOUNDED: i32 = 1;
pub const INCAPACITATED: i32 = 2;
pub const STUNNED: i32 = 3;
pub const SLEEPING: i32 = 4;
pub const RESTING: i32 = 5;
pub const SITTING: i32 = 6;
pub const FIGHTING: i32 = 7;
pub const STANDING: i32 = 8;

/// `LVL_IMMORT`: the pack has no immortals, so a level at or above this is
/// never reached, and a command that needs it never matches.
pub const LVL_IMMORT: i32 = 31;

/// The door commands, in `cmd_door[]` order (`SCMD_OPEN`..`SCMD_PICK`).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum DoorCmd {
    Open,
    Close,
    Unlock,
    Lock,
    Pick,
}

/// `do_drop`'s three modes.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum DropMode {
    Drop,
    Junk,
    Donate,
}

/// `do_spec_comm`'s two modes.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum SpecComm {
    Whisper,
    Ask,
}

/// `do_gen_comm`'s channels.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Channel {
    Holler,
    Shout,
    Gossip,
    Auction,
    Grats,
    Gemote,
}

/// What a command does when a mob runs it.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Handler {
    /// Nothing happens for an NPC.
    Noop,
    /// The C does something the pack does not model; the use is counted.
    Unmodelled,
    /// `do_move` toward this direction (`0..10`, the C's `NORTH`..`SOUTHWEST`).
    Move(usize),
    Door(DoorCmd),
    Drop(DropMode),
    Say,
    Tell,
    SpecComm(SpecComm),
    GenComm(Channel),
    /// `do_echo`: `true` for `emote`, `false` for the immortal `echo`.
    Echo(bool),
    Get,
    Give,
    Put,
    Wear,
    Wield,
    Grab,
    Remove,
    Sit,
    Rest,
    Sleep,
    Wake,
    Stand,
    Follow,
    Unfollow,
    /// `do_hit` (and `do_kill`, which falls through to it for everyone here).
    Hit,
    Assist,
    Flee,
    Enter,
    Sacrifice,
}

/// One row of `cmd_info[]`.
#[derive(Debug, Clone, Copy)]
pub struct Cmd {
    pub name: &'static str,
    /// The key the command list is sorted by; only `do_commands` reads it.
    #[allow(dead_code)]
    pub sort_as: &'static str,
    pub min_position: i32,
    pub handler: Handler,
    pub min_level: i32,
}

impl Cmd {
    const fn new(
        name: &'static str,
        sort_as: &'static str,
        min_position: i32,
        handler: Handler,
        min_level: i32,
    ) -> Self {
        Self {
            name,
            sort_as,
            min_position,
            handler,
            min_level,
        }
    }
}

