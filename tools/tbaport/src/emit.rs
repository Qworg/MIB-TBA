//! YAML emission.
//!
//! The output is produced by serialising the **real** content types from
//! `mib-stdlib` and `mib-tba`, so the files cannot drift from the schema the
//! engine loads. `serde_yaml` writes `BTreeMap` keys in their natural
//! (deterministic) order, so converting the same source twice is byte-identical.

use std::collections::BTreeMap;
use std::path::Path;

use mib_stdlib::content::{
    AreasFile, HelpFile, ItemsFile, NpcsFile, QuestsFile, RoomDef, RoomId, RoomsFile,
};
use mib_tba::content::{ShopsFile, SocialsFile, TbaItemsFile, TbaNpcStatsFile, ZonesFile};
use mib_tba::triggers::content::TriggersFile;

use crate::error::{ConvertError, Result};

/// The complete converted world, ready to write.
#[derive(Debug, Clone)]
pub struct OutputBundle {
    pub areas: AreasFile,
    pub rooms: RoomsFile,
    pub npcs: NpcsFile,
    pub items: ItemsFile,
    pub quests: QuestsFile,
    pub help: HelpFile,
    pub zones: ZonesFile,
    pub npc_stats: TbaNpcStatsFile,
    pub tba_items: TbaItemsFile,
    pub shops: ShopsFile,
    pub socials: SocialsFile,
    /// `tba.triggers` — every DG script and every owner's trigger list, sharded
    /// by zone.
    pub triggers: TriggersFile,
    /// The zone file each `triggers.attachments` owner lives in, which picks
    /// the shard of its list. An owner absent here is placed by its vnum.
    pub attachment_zones: BTreeMap<String, u32>,
}

impl OutputBundle {
    /// An empty bundle with every section present.
    pub fn empty() -> Self {
        Self {
            areas: AreasFile {
                areas: Default::default(),
            },
            rooms: RoomsFile {
                rooms: Default::default(),
            },
            npcs: NpcsFile {
                npcs: Default::default(),
            },
            items: ItemsFile {
                items: Default::default(),
            },
            quests: QuestsFile {
                quests: Default::default(),
            },
            help: HelpFile {
                topics: Default::default(),
            },
            zones: ZonesFile {
                zones: Default::default(),
            },
            npc_stats: TbaNpcStatsFile {
                npc_stats: Default::default(),
            },
            tba_items: TbaItemsFile {
                items: Default::default(),
            },
            shops: ShopsFile {
                shops: Default::default(),
            },
            socials: SocialsFile {
                socials: Default::default(),
            },
            triggers: TriggersFile::default(),
            attachment_zones: BTreeMap::new(),
        }
    }
}

/// Header prepended to every generated file. Fixed text keeps output stable.
const HEADER: &str = "# Generated by tbaport from tbaMUD world files. Do not edit by hand.\n";

/// Serialise one value with the provenance header.
fn dump<T: serde::Serialize>(value: &T) -> Result<String> {
    let body = serde_yaml::to_string(value)?;
    Ok(format!("{HEADER}{body}"))
}

fn write_file(dir: &Path, name: &str, contents: &str) -> Result<()> {
    let path = dir.join(name);
    std::fs::write(&path, contents).map_err(|source| ConvertError::Io { path, source })
}

/// One `stdlib.rooms.<zone>.yaml` shard per converted area (TBA-E01).
///
/// The engine discovers `stdlib.rooms.*.yaml` and merges them in
/// lexicographical path order, so sharding does not change the loaded room
/// set. Each shard is a complete `RoomsFile`; the zone number is the suffix of
/// the room's `tba_<zone>` area id, and shards are emitted in ascending zone
/// order so the staging directory is deterministic.
fn room_shards(rooms: &RoomsFile) -> Result<Vec<(String, String)>> {
    let mut by_zone: BTreeMap<u32, BTreeMap<RoomId, RoomDef>> = BTreeMap::new();
    let mut fallback: BTreeMap<String, BTreeMap<RoomId, RoomDef>> = BTreeMap::new();
    for (id, def) in &rooms.rooms {
        match def
            .area
            .as_ref()
            .strip_prefix("tba_")
            .and_then(|zone| zone.parse::<u32>().ok())
        {
            Some(zone) => {
                by_zone
                    .entry(zone)
                    .or_default()
                    .insert(id.clone(), def.clone());
            }
            // Defensive: an area id that is not `tba_<number>` still gets a
            // deterministic shard rather than being dropped.
            None => {
                fallback
                    .entry(def.area.to_string())
                    .or_default()
                    .insert(id.clone(), def.clone());
            }
        }
    }

    let mut files = Vec::with_capacity(by_zone.len() + fallback.len());
    for (zone, rooms) in by_zone {
        files.push((
            format!("stdlib.rooms.{zone}.yaml"),
            dump(&RoomsFile { rooms })?,
        ));
    }
    for (area, rooms) in fallback {
        let suffix = area.replace(['/', '\\', ' '], "_");
        files.push((
            format!("stdlib.rooms.{suffix}.yaml"),
            dump(&RoomsFile { rooms })?,
        ));
    }
    Ok(files)
}

/// The zone of an attachments key (`npc:tba_npc_3`, `item:tba_item_16`,
/// `room:tba.22`) with no recorded zone: Circle's vnum banding of the owner.
/// An unparsable key lands in zone 0 rather than being dropped.
fn banded_owner_zone(owner: &str) -> u32 {
    owner
        .rsplit(['_', '.'])
        .next()
        .and_then(|vnum| vnum.parse::<i32>().ok())
        .map_or(0, crate::triage::vnum_zone)
}

/// One `tba.triggers.<zone>.yaml` shard per zone that has a trigger record or
/// an owner.
///
/// A trigger's zone is Circle's vnum banding (`vnum / 100`), which the triage
/// confirms equals the `.trg` file's zone for the whole corpus. An owner's
/// list goes in the shard of the zone file the owner lives in, so each owner key appears
/// in exactly one shard (the pack loader rejects a duplicate key) while the
/// list may name triggers defined in other zones' shards: the sections are
/// validated after the shards are merged. Shards are emitted in ascending
/// zone order so the staging directory is deterministic.
fn trigger_shards(
    triggers: &TriggersFile,
    owner_zones: &BTreeMap<String, u32>,
) -> Result<Vec<(String, String)>> {
    let mut by_zone: BTreeMap<u32, TriggersFile> = BTreeMap::new();
    for (id, def) in &triggers.triggers {
        by_zone
            .entry(crate::triage::vnum_zone(def.vnum))
            .or_default()
            .triggers
            .insert(id.clone(), def.clone());
    }
    for (owner, list) in &triggers.attachments {
        by_zone
            .entry(
                owner_zones
                    .get(owner)
                    .copied()
                    .unwrap_or_else(|| banded_owner_zone(owner)),
            )
            .or_default()
            .attachments
            .insert(owner.clone(), list.clone());
    }
    let mut files = Vec::with_capacity(by_zone.len());
    for (zone, shard) in by_zone {
        files.push((format!("tba.triggers.{zone}.yaml"), dump(&shard)?));
    }
    Ok(files)
}

/// Every section file for a bundle, in deterministic order.
fn section_files(bundle: &OutputBundle) -> Result<Vec<(String, String)>> {
    let mut files = vec![
        ("stdlib.areas.yaml".to_owned(), dump(&bundle.areas)?),
        ("stdlib.npcs.yaml".to_owned(), dump(&bundle.npcs)?),
        ("stdlib.items.yaml".to_owned(), dump(&bundle.items)?),
        ("stdlib.quests.yaml".to_owned(), dump(&bundle.quests)?),
        ("stdlib.help.yaml".to_owned(), dump(&bundle.help)?),
        ("tba.zones.yaml".to_owned(), dump(&bundle.zones)?),
        ("tba.npc_stats.yaml".to_owned(), dump(&bundle.npc_stats)?),
        ("tba.items.yaml".to_owned(), dump(&bundle.tba_items)?),
        ("tba.shops.yaml".to_owned(), dump(&bundle.shops)?),
        ("tba.socials.yaml".to_owned(), dump(&bundle.socials)?),
    ];
    files.extend(room_shards(&bundle.rooms)?);
    files.extend(trigger_shards(&bundle.triggers, &bundle.attachment_zones)?);
    Ok(files)
}

/// Write each section file into `dir`, returning the file names written in
/// order.
pub fn write_bundle(dir: &Path, bundle: &OutputBundle) -> Result<Vec<String>> {
    std::fs::create_dir_all(dir).map_err(|source| ConvertError::Io {
        path: dir.to_path_buf(),
        source,
    })?;

    let files = section_files(bundle)?;
    let mut written = Vec::with_capacity(files.len());
    for (name, contents) in files {
        write_file(dir, &name, &contents)?;
        written.push(name);
    }
    Ok(written)
}

/// Serialise a bundle in memory (used by tests and `--validate-only`).
pub fn render(bundle: &OutputBundle) -> Result<Vec<(String, String)>> {
    section_files(bundle)
}
